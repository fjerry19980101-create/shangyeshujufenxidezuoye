"""lab06 价值流（VSM）数据：银行贷款审批流程。

教材 3.6.2 给出的流程与耗时为确定数值：

    1 客户申请并提交审核资料  1 天
    2 银行专人审核            2 天   ← 行业标杆 0.5 天
    3 客户信用评估            2 天   ← 行业标杆 0.5 天
    4 银行审批决策            1 天
    5 签约与放款              1 天
    当前总周期 7 天；行业 TOP 银行第 2、3 个节点各 0.5 天，其余节点无差异。

因此本实验数据直接录入书中数值，不做随机模拟。
"""

from __future__ import annotations

import pandas as pd

NODES = [
    {
        "序号": 1,
        "流程节点": "客户申请并提交审核资料",
        "当前耗时": 1.0,
        "行业标杆": 1.0,
        "价值判定": "必要非增值",
        "业务问题": "资料常出错或不齐全，客户需多次往返银行",
        "改进措施": "改为线上申请，系统实时校验资料完整性与准确性并即时反馈",
    },
    {
        "序号": 2,
        "流程节点": "银行专人审核",
        "当前耗时": 2.0,
        "行业标杆": 0.5,
        "价值判定": "纯非增值",
        "业务问题": "审核任务繁重、多项事务并行处理，单任务耗时长",
        "改进措施": "引入 RPA / 系统自动化辅助或替代人工审核",
    },
    {
        "序号": 3,
        "流程节点": "客户信用评估",
        "当前耗时": 2.0,
        "行业标杆": 0.5,
        "价值判定": "纯非增值",
        "业务问题": "需查阅大量客户信息、易疲劳；部分信息手工录入，系统流程繁琐",
        "改进措施": "开发 AI 信用评估算法并集成，仅复杂/异常情况转人工",
    },
    {
        "序号": 4,
        "流程节点": "银行审批决策",
        "当前耗时": 1.0,
        "行业标杆": 1.0,
        "价值判定": "增值",
        "业务问题": "—",
        "改进措施": "维持现有流程",
    },
    {
        "序号": 5,
        "流程节点": "签约与放款",
        "当前耗时": 1.0,
        "行业标杆": 1.0,
        "价值判定": "增值",
        "业务问题": "—",
        "改进措施": "维持现有流程",
    },
]


def vsm_table() -> pd.DataFrame:
    """节点明细：当前耗时、标杆耗时、差距与价值判定。"""
    df = pd.DataFrame(NODES)
    df["差距"] = (df["当前耗时"] - df["行业标杆"]).round(2)
    return df


def vsm_summary(df: pd.DataFrame | None = None) -> pd.DataFrame:
    """总周期、增值时间与增值占比（当前 vs 优化后）。"""
    df = vsm_table() if df is None else df
    current_total = df["当前耗时"].sum()
    target_total = df["行业标杆"].sum()
    value_added = df.loc[df["价值判定"] == "增值", "当前耗时"].sum()

    return pd.DataFrame(
        {
            "指标": ["总周期（天）", "增值时间（天）", "增值时间占比", "可压缩时间（天）"],
            "当前流程": [
                current_total,
                value_added,
                value_added / current_total,
                df["差距"].sum(),
            ],
            "优化目标": [
                target_total,
                value_added,
                value_added / target_total,
                0.0,
            ],
        }
    )


if __name__ == "__main__":
    print(vsm_table())
    print(vsm_summary())
