"""lab04 模拟数据：2020 年 6/7 月财务费用结构。

教材 3.4.2 只给出结论与趋势（总费用 7 月比 6 月高 5%，管理费用显著增长，
管理费用明细中"培训与发展""咨询费"环比增长超过 5%），未附金额明细。

这里按上述比例构造两个月费用结构，保证：
- 6 月总费用 1,580,000 元，7 月 1,659,000 元，环比 +5.0%；
- 三项期间费用：管理费用 +80,000（显著）、销售费用 +14,000（小幅）、
  财务费用 -15,000（小幅下降）；
- 管理费用明细合计从 620,000 增至 700,000，仅培训与发展、咨询费环比超过 5%。

数据为模拟还原，不代表企业真实账目。
"""

from __future__ import annotations

import pandas as pd

# 三项期间费用（金额单位：元）
PERIOD_EXPENSES = pd.DataFrame(
    {
        "费用项": ["管理费用", "销售费用", "财务费用"],
        "6月": [620_000, 560_000, 400_000],
        "7月": [700_000, 574_000, 385_000],
    }
)

# 管理费用明细
MANAGEMENT_DETAIL = pd.DataFrame(
    {
        "明细项": ["培训与发展", "咨询费", "办公租金", "职工薪酬", "差旅费", "折旧摊销", "办公费"],
        "6月": [90_000, 40_000, 150_000, 220_000, 60_000, 40_000, 20_000],
        "7月": [130_000, 75_000, 150_000, 223_200, 61_000, 40_000, 20_800],
    }
)

# 异常判定阈值：环比增长率超过 5%
ANOMALY_THRESHOLD = 0.05

# 业务属性：长期影响 / 临时需求（教材访谈结论）
BUSINESS_NATURE = {
    "培训与发展": "长期（持续 1~2 年，外部高级讲师费用增加）",
    "咨询费": "临时（7 月总部 HR 数字化项目外采，交付即结束）",
}


def add_growth(df: pd.DataFrame, name_col: str) -> pd.DataFrame:
    """增加环比金额、环比增长率、对总增量的贡献度。"""
    total_increase = df["7月"].sum() - df["6月"].sum()
    out = df.copy()
    out["环比增量"] = out["7月"] - out["6月"]
    out["环比增长率"] = out["7月"] / out["6月"] - 1
    out["对总增量贡献"] = out["环比增量"] / total_increase
    return out


if __name__ == "__main__":
    print(add_growth(PERIOD_EXPENSES, "费用项"))
    print(add_growth(MANAGEMENT_DETAIL, "明细项"))
